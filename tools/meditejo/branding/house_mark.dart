// The house mark: Meditejo's fixed launcher icon (decision 21, the
// shelter), kept as frozen geometry so the icon never changes when the
// generator does.
//
//   dart run tools/meditejo/branding/house_mark.dart           # JSON -> SVGs
//   dart run tools/meditejo/branding/house_mark.dart --freeze [SEED]
//
// --freeze builds SEED (default m-2026-10-26) with the generator and writes
// assets/branding/house_mark.json. Do it once, deliberately: the JSON is the
// icon's source of truth. Without it, the SVGs are written from the JSON:
//   assets/branding/house_mark.svg         the adaptive icon: tile + mark,
//                                          108 × 108, mark in the safe zone
//   assets/branding/house_mark_glyph.svg   the same mark alone, one colour
//   assets/branding/house_mark_square.svg  a square icon (iOS, legacy
//                                          mipmaps, in-app), whole canvas
//                                          visible
// make_icons.py runs this, then renders every platform's icon from them.
import 'dart:io';

import 'package:medito/services/identity/mark_generator.dart';
import 'package:medito/services/identity/mark_outline.dart';
import 'package:medito/services/identity/mark_spec.dart';
import 'package:medito/services/identity/palettes.dart';

const defaultSeed = 'm-2026-10-26';
const json = 'assets/branding/house_mark.json';

/// The icon's palette (decision 21: Tidewater).
const paletteId = 'tide';

/// An adaptive icon is 108 dp; the launcher shows the central 72, and keeps
/// content inside a 66 dp circle. The mark's tile maps onto the central 72,
/// and its content is shrunk to 0.9 about the centre, as the exploration's
/// preview did.
const canvas = 108.0, visible = 72.0, content = 0.9;

/// Maps tile units onto the icon: the mark's bounding box is centred (the
/// shelter's tile composition sits low, which a circle mask exaggerates),
/// then the tile's side becomes [visible] dp, shrunk to [content].
(double, double) Function((double, double)) toIcon(
  double visible,
  (double, double) centre,
) =>
    (p) => (
      canvas / 2 + (p.$1 - centre.$1) * visible * content,
      canvas / 2 + (p.$2 - centre.$2) * visible * content,
    );

/// The centre of [mark]'s settled bounding box, in tile units.
(double, double) boxCentre(MarkSpec mark) {
  var x0 = double.infinity, y0 = double.infinity;
  var x1 = -double.infinity, y1 = -double.infinity;
  settledOutline(
    mark,
    map: (p) {
      x0 = p.$1 < x0 ? p.$1 : x0;
      x1 = p.$1 > x1 ? p.$1 : x1;
      y0 = p.$2 < y0 ? p.$2 : y0;
      y1 = p.$2 > y1 ? p.$2 : y1;
      return p;
    },
  );
  return ((x0 + x1) / 2, (y0 + y1) / 2);
}

String hex(int argb) =>
    '#${(argb & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';

void main(List<String> args) {
  if (args.isNotEmpty && args.first == '--freeze') {
    final seed = args.length > 1 ? args[1] : defaultSeed;
    final mark = MarkGenerator.build(seed);
    File(json).writeAsStringSync('${mark.encode()}\n');
    stdout.writeln('Froze $seed (${mark.family.name} ${mark.type}) into $json');
  }
  final mark = MarkSpec.decode(File(json).readAsStringSync());
  final palette = IdentityPalettes.byId(paletteId);
  final centre = boxCentre(mark);
  final shapes = settledOutline(mark, map: toIcon(visible, centre));
  final square = settledOutline(mark, map: toIcon(canvas, centre));
  int fill(String role) => switch (role) {
    'form' => palette.form,
    'stroke' => palette.stroke,
    'accent' => palette.accent,
    _ => palette.tile,
  };
  const head =
      '<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" '
      'viewBox="0 0 108 108">\n';
  final note =
      '  <!-- Meditejo house mark ${mark.seed} (${mark.type}), generated by '
      'tools/meditejo/branding/house_mark.dart from house_mark.json. -->\n';
  File('assets/branding/house_mark.svg').writeAsStringSync(
    '$head$note'
    '  <rect width="108" height="108" fill="${hex(palette.tile)}"/>\n'
    '${[for (final s in shapes) '  <path fill="${hex(fill(s.role))}" d="${s.path}"/>\n'].join()}'
    '</svg>\n',
  );
  File('assets/branding/house_mark_glyph.svg').writeAsStringSync(
    '$head$note'
    '${[for (final s in shapes) '  <path fill="#FFFFFF" d="${s.path}"/>\n'].join()}'
    '</svg>\n',
  );
  File('assets/branding/house_mark_square.svg').writeAsStringSync(
    '$head$note'
    '  <rect width="108" height="108" fill="${hex(palette.tile)}"/>\n'
    '${[for (final s in square) '  <path fill="${hex(fill(s.role))}" d="${s.path}"/>\n'].join()}'
    '</svg>\n',
  );
  stdout.writeln('Wrote assets/branding/house_mark{,_glyph,_square}.svg');
}
