#!/usr/bin/env python3
"""Write the bells' synthesis recipes as Dart, for the in-app bell maker.

The ten synthesised bells come from tools/meditejo/generate_bells.py. The app
can make a bell of its own (BJS-587) by running the same modal synthesis in
Dart, starting from one of them, so Dart needs each bell's modes: frequency,
amplitude, decay, beat, swell-in, phase and pitch glide, and its strike. This
imports the generator, swaps its render() and strike() for recorders, calls
each sound's build, and writes what they were given, so the numbers come from
the generator and not from a copy of its tables.

The eleventh bell, Medito's "Swell bell" (assets/audio/session_bell_v2.wav),
is a recording, so its two modes are the ones measured from the WAV for
identity round 5 (docs/fork/design/identity/round5/bell_params.py).

    python3 tools/meditejo/bell_recipes.py           # write lib/services/bells/bell_recipes.dart
    python3 tools/meditejo/bell_recipes.py --check   # fail when the file is stale

The gong's noise wash is built inside gong() and cannot be recorded; its
numbers are repeated here (WASH) and --check cannot see them move.
"""
import argparse
import importlib.util
import math
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parents[1] / 'lib' / 'services' / 'bells' / 'bell_recipes.dart'

# generate_bells.gong(): lowpass Hz, level, swell-in tau, decay tau.
WASH = {'gong': (1400.0, 0.26, 0.25, 1.6)}

# Measured from session_bell_v2.wav (round 5): f, a, tau, beat, rise.
SWELL = {
    'modes': [
        {'f': 220.7, 'a': 1.0, 'tau': 1.228, 'beat': 0.24, 'rise': 0.4257},
        {'f': 592.2, 'a': 0.202, 'tau': 1.079, 'beat': 0.22, 'rise': 0.1625},
    ],
    'hit': {'lowpass': 300.0, 'tau': 0.02, 'level': 0.05, 'attack': 1.37,
            'seconds': 0.15},
}


def load_generator():
    spec = importlib.util.spec_from_file_location(
        'generate_bells', HERE / 'generate_bells.py')
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    return gen


def record(gen):
    seen = {}

    def render(rate, seconds, modes):
        if modes:
            seen['modes'] = seen.get('modes', []) + [{
                'f': m.f, 'a': m.a, 'tau': m.tau, 'beat': m.beat,
                'rise': m.rise, 'split': m.split, 'phase': m.phase,
                'glide': m.glide,
            } for m in modes]
            return [0.0]
        return [0.0] * round(rate * seconds)  # the gong's wash fills this in place

    def strike(rate, seconds, rng, lowpass_hz, tau, level, attack=0.0005):
        seen['hit'] = {'lowpass': lowpass_hz, 'tau': tau, 'level': level,
                       'attack': attack, 'seconds': seconds}
        return [0.0]

    gen.render, gen.strike = render, strike
    out = {}
    for sound in gen.SOUNDS:
        seen.clear()
        sound.build(sound.rate, sound.seconds)
        out[sound.slug] = {'modes': sorted(seen['modes'], key=lambda m: m['f']),
                           'hit': seen['hit']}
    return out


def num(v):
    return repr(float(v))


def mode_dart(m):
    parts = [num(m['f']), num(m['a']), num(m['tau'])]
    if m['rise']:
        parts.append(f"rise: {num(m['rise'])}")
    if m['beat']:
        parts.append(f"beat: {num(m['beat'])}")
        parts.append(f"split: {num(m.get('split', 0.3))}")
    parts.append(f"phase: {num(m['phase'])}")
    if m.get('glide'):
        drop, gt = m['glide']
        parts.append(f'glideDrop: {num(drop)}')
        parts.append(f'glideTau: {num(gt)}')
    return f"BellMode({', '.join(parts)}),"


def dart(recipes):
    lines = [
        '// GENERATED by tools/meditejo/bell_recipes.py from generate_bells.py;',
        '// do not edit. Run the script again after changing a bell.',
        '// dart format off',
        '',
        "import 'package:medito/services/bells/bell_recipe.dart';",
        '',
        '/// Each shipped bell\'s modes and strike, by preset (the keys of',
        '/// `BellFigure.family`).',
        'const Map<String, BellRecipe> bellRecipes = {',
    ]
    for slug, r in recipes.items():
        h = r['hit']
        lines.append(f"  '{slug}': BellRecipe(")
        lines.append('    modes: [')
        lines += [f'      {mode_dart(m)}' for m in r['modes']]
        lines.append('    ],')
        lines.append(
            f"    hit: BellHit({num(h['lowpass'])}, {num(h['tau'])}, "
            f"{num(h['level'])}, {num(h['attack'])}, {num(h['seconds'])}),")
        if slug in WASH:
            lp, level, rise, tau = WASH[slug]
            lines.append(f'    wash: BellWash({num(lp)}, {num(level)}, '
                         f'{num(rise)}, {num(tau)}),')
        lines.append('  ),')
    lines += ['};', '']
    return '\n'.join(lines)


def generate():
    recipes = {}
    swell = dict(SWELL)
    swell['modes'] = [dict(m, split=0.3, glide=None,
                           phase=math.fmod(m['f'] * 7.3, 2 * math.pi))
                      for m in SWELL['modes']]
    recipes['swell'] = swell
    recipes.update(record(load_generator()))
    return dart(recipes)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true',
                        help='compare with the file on disk')
    args = parser.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f'stale: {OUT}; run tools/meditejo/bell_recipes.py',
                  file=sys.stderr)
            return 1
        print('bell recipes are current')
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(OUT)
    return 0


if __name__ == '__main__':
    sys.exit(main())
